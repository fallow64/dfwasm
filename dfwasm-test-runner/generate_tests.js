function write(module_name, wat, cases) {
  const wat_path = path.join(SINGLE_TEST_PATH, `${module_name}.wat`);
  fs.writeFileSync(wat_path, wat, {
    flag: "w",
  });

  const cases_path = path.join(SINGLE_TEST_PATH, `${module_name}.test`);
  fs.writeFileSync(cases_path, cases, {
    flag: "w",
  });
}

function simple(type, should_skip_case) {
  for (const instruction of INSTRUCTIONS[type]) {
    const function_name = instruction.instr.replace(".", "_");
    const module_name = `single_${function_name}`;

    const instr_asm = instruction.instr;
    const instr_args = instruction.args;
    const instr_res = instruction.res;

    let function_body;
    if (instr_args.length === 2) {
      function_body = `(local.get 0) (local.get 1) ${instr_asm}`;
    } else if (instr_args.length === 1) {
      function_body = `(local.get 0) ${instr_asm}`;
    } else {
      throw new Error("Invalid number of arguments");
    }

    const signature = `(param ${instr_args.join(" ")}) (result ${instr_res.join(
      " "
    )})`;

    const wat = `(module
  (func $${function_name} ${signature}
    ${function_body}
  )

  (export "${function_name}" (func $${function_name}))
)`;

    let test_cases_file = "";
    for (const test_case of TEST_CASES[type][instr_args.length]) {
      if (should_skip_case(test_case, instruction.instr)) {
        continue;
      }

      const test_case_str = test_case.map((x) => x.toString()).join(" ");
      const test = `${function_name} ${test_case_str}`;
      test_cases_file += `${test}\n`;
    }

    write(module_name, wat, test_cases_file);
  }
}

